/**
 * 本地补充翻译（locales patch）
 *
 * 为什么需要这个文件：
 * - 语言包 `@electerm/electerm-locales` 是**外部 npm 依赖**，无法就地新增 key；
 * - `window.translate(key)` 在缺失时返回「首字母大写的 key 原文」（如 dbType → "DbType"），
 *   于是新功能引入的文案会直接暴露英文 key；
 * - 实测：15 种语言**一致缺失 113 个 key**（remote-monitor / sftp 代码对比 / 设置面板 /
 *   书签表单 / 数据库连接等新功能引入，上游语言包尚未收录）。
 *
 * 合并规则（见 `src/app/lib/locales.js`）：
 *   1. 先以 `en` 兜底补齐所有语言缺失项（避免任何语言出现驼峰 key 原文）；
 *   2. 再用该语言自己的词条覆盖兜底（如 `zh_cn`）；
 *   3. **语言包已有的翻译永远优先**，本文件只补缺失项，不覆盖上游。
 *
 * 新增词条时请同步 `en` 与 `zh_cn`，并运行仓库内的缺失扫描脚本复核。
 */

