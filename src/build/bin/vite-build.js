#!/bin/bash
const { exec, cd } = require('shelljs')
const { resolve } = require('path')
const fs = require('fs')
const p = resolve(__dirname, '../vite')
cd(p)

// Remove previously built versioned bundles before recompiling so old-version
// files (e.g. js/electerm-3.15.186.js, css/style-3.15.186.css) don't
// accumulate in work/app/assets across releases. This is the surgical
// alternative to Vite's emptyOutDir: it only clears the Vite-owned,
// fully-regenerated subdirs, so it never wipes files placed by other steps.
//
//   js/ css/ chunk/ assets/  -> Vite regenerates these every build
//   icons/  -> owned by copy.js (rm -rf + cp), must NOT be deleted
//   images/ index.html       -> regenerated by Vite/pug, not versioned, safe to keep
//
// fs.rmSync can be intercepted by the dev safe-delete shim on bulk deletes
// (the chunk/ dir holds ~270 files), so fall back to native /bin/rm.
const assetsDir = resolve(__dirname, '../../../work/app/assets')
;['js', 'css', 'chunk', 'assets'].forEach((sub) => {
  const target = resolve(assetsDir, sub)
  try {
    fs.rmSync(target, { recursive: true, force: true })
  } catch (e) {
    try {
      exec(`/bin/rm -rf ${JSON.stringify(target)}`)
    } catch (e2) {
      // best-effort: Vite overwrites what it owns on the build below
    }
  }
})

exec('npm run build')
